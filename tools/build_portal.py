#!/usr/bin/env python3
"""Build the self-contained AP page from readable local sources. No network."""
from pathlib import Path
import argparse
import re
import base64
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true',help='Fail if generated firmware and preview differ from the canonical sources')
args=parser.parse_args()
ROOT=Path(__file__).resolve().parents[1]
html=(ROOT/'web/portal.html').read_text()
css=(ROOT/'web/portal.css').read_text()+'\n'+(ROOT/'web/pit.css').read_text()
font=base64.b64encode((ROOT/'assets/portal/storm-dot.woff').read_bytes()).decode()
css="@font-face{font-family:'Storm Dot';src:url(data:font/woff;base64,"+font+") format('woff');font-weight:400;font-style:normal;font-display:swap;}\n"+css
js=(ROOT/'web/portal.js').read_text()
art_counts={}
def art(match):
    name=match.group(1)
    svg=(ROOT/'assets/portal'/f'{name}.svg').read_text()
    svg=re.sub(r'<\?xml[^>]*\?>','',svg).strip()
    art_counts[name]=art_counts.get(name,0)+1
    ids=re.findall(r'id="([^"]+)"',svg)
    for old in ids:
        new=f'{old}-{art_counts[name]}'
        svg=svg.replace(f'id="{old}"',f'id="{new}"').replace(f'url(#{old})',f'url(#{new})').replace(f'href="#{old}"',f'href="#{new}"')
    return svg
html=html.replace('<!-- PIT_CONTROLS -->',(ROOT/'web/pit.html').read_text()).replace('/* PIT_SCRIPT */',(ROOT/'web/pit.js').read_text())
html=html.replace('/* PRESENTATION_SCRIPT */',(ROOT/'web/presentation.js').read_text())
html=re.sub(r'<!-- ART:([a-z-]+) -->',art,html)
html=html.replace('/* INLINE_STYLE */',css).replace('/* INLINE_SCRIPT */',js)
assert 'INLINE_' not in html and '<!-- ART:' not in html
assert ')STORM"' not in html
# Keep exact script bytes for the source/preview identity test.
outputs={
 'src/services/storm_page.h':'#pragma once\n// Generated by tools/build_portal.py from web/ and assets/portal/.\nstatic const char STORM_PAGE[] PROGMEM=R"STORM('+html+')STORM";\n',
 'output/stormDASH/portal.html':html,
 'output/stormDASH/portal.js':re.search(r'<script>(.*?)</script>',html,re.S).group(1),
}
update=(ROOT/'web/update.html').read_text()
update=update.replace('/* INLINE_STYLE */',(ROOT/'web/portal.css').read_text()+'\n'+(ROOT/'web/update.css').read_text()).replace('/* PRESENTATION_SCRIPT */',(ROOT/'web/presentation.js').read_text()).replace('/* UPDATE_SCRIPT */',(ROOT/'web/update.js').read_text())
assert '{{TOKEN}}' in update and '/* INLINE_' not in update
outputs['src/services/storm_update_page.h']='#pragma once\n// Generated by tools/build_portal.py. Token replaced by existing GET handler.\nstatic const char STORM_UPDATE_PAGE[] PROGMEM=R"UPDATE('+update+')UPDATE";\n'
outputs['output/stormDASH/update.html']=update
for name,content in outputs.items():
 path=ROOT/name
 if args.check:
  if not path.exists() or path.read_text()!=content:
   raise SystemExit(f'Outdated {name}; run python3 tools/build_portal.py')
 else:
  path.parent.mkdir(parents=True,exist_ok=True)
  path.write_text(content)
print(f'Self-contained AP portal {"verified" if args.check else "built"}: {len(html.encode()):,} bytes, no external assets.')
