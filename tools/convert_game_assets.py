#!/usr/bin/env python3
"""Convert small PNG/WebP game art to compile-time RGB565 C++ assets.

Designed for macOS' system Python.  Install Pillow once with:
    python3 -m pip install --user pillow

Transparent pixels become a configurable RGB565 colour key.  The firmware can
therefore blit the generated arrays without JPEG decoding or heap allocation.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

try:
    from PIL import Image
except ImportError as exc:  # pragma: no cover - user-facing dependency guard
    raise SystemExit(
        "Pillow non trovato. Esegui: python3 -m pip install --user pillow"
    ) from exc


def identifier(path: Path) -> str:
    name = re.sub(r"[^A-Za-z0-9]+", "_", path.stem).strip("_").lower()
    if not name:
        name = "asset"
    if name[0].isdigit():
        name = f"asset_{name}"
    return name


def parse_rgb(value: str) -> tuple[int, int, int]:
    text = value.strip().lstrip("#")
    if len(text) != 6 or any(char not in "0123456789abcdefABCDEF" for char in text):
        raise argparse.ArgumentTypeError("il colore deve essere RRGGBB")
    return int(text[0:2], 16), int(text[2:4], 16), int(text[4:6], 16)


def rgb565(red: int, green: int, blue: int) -> int:
    return ((red & 0xF8) << 8) | ((green & 0xFC) << 3) | (blue >> 3)


def convert(path: Path, key: tuple[int, int, int], max_side: int) -> tuple[int, int, list[int]]:
    with Image.open(path) as source:
        image = source.convert("RGBA")
        if image.width > max_side or image.height > max_side:
            image.thumbnail((max_side, max_side), Image.Resampling.LANCZOS)
        pixels: list[int] = []
        key565 = rgb565(*key)
        for red, green, blue, alpha in image.getdata():
            pixels.append(key565 if alpha < 128 else rgb565(red, green, blue))
        return image.width, image.height, pixels


def emit_array(name: str, width: int, height: int, pixels: list[int]) -> str:
    rows = []
    for start in range(0, len(pixels), 12):
        chunk = ", ".join(f"0x{value:04X}" for value in pixels[start : start + 12])
        rows.append(f"    {chunk},")
    body = "\n".join(rows)
    return f"""inline constexpr uint16_t {name}_width = {width};
inline constexpr uint16_t {name}_height = {height};
inline constexpr uint16_t {name}_pixels[] PROGMEM = {{
{body}
}};
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("inputs", nargs="+", type=Path, help="PNG/WebP da convertire")
    parser.add_argument("-o", "--output", required=True, type=Path, help="header .h generato")
    parser.add_argument("--namespace", default="trail_assets", help="namespace C++")
    parser.add_argument("--color-key", type=parse_rgb, default=(255, 0, 255), help="RRGGBB")
    parser.add_argument("--max-side", type=int, default=240, help="ridimensionamento massimo")
    args = parser.parse_args()

    if not 1 <= args.max_side <= 1024:
        parser.error("--max-side deve essere fra 1 e 1024")

    used: set[str] = set()
    assets: list[str] = []
    for path in args.inputs:
        if not path.is_file():
            parser.error(f"file non trovato: {path}")
        name = identifier(path)
        if name in used:
            parser.error(f"nome asset duplicato dopo normalizzazione: {name}")
        used.add(name)
        width, height, pixels = convert(path, args.color_key, args.max_side)
        assets.append(emit_array(name, width, height, pixels))

    key565 = rgb565(*args.color_key)
    output = "\n".join(
        [
            "// Generated by tools/convert_game_assets.py. Do not edit by hand.",
            "#pragma once",
            "#include <stdint.h>",
            "#ifndef PROGMEM",
            "#define PROGMEM",
            "#endif",
            f"namespace {args.namespace} {{",
            f"inline constexpr uint16_t color_key = 0x{key565:04X};",
            "",
            *assets,
            f"}}  // namespace {args.namespace}",
            "",
        ]
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output, encoding="utf-8")
    print(f"Creato {args.output} con {len(assets)} asset RGB565")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
