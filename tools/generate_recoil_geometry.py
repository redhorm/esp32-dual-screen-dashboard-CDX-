#!/usr/bin/env python3
"""Generate firmware pixel coordinates from the delivered Fusion mask contract."""
from pathlib import Path
import argparse, hashlib, json

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'references/recoil/Coordinate_luci_160x80.json'
TARGET = ROOT / 'src/app/recoil_geometry.h'

def inside(x, y, poly):
    yes = False
    for (ax, ay), (bx, by) in zip(poly, poly[1:] + poly[:1]):
        if (ay > y) != (by > y) and x < (bx-ax)*(y-ay)/(by-ay)+ax:
            yes = not yes
    return yes

def generate():
    data = json.loads(SOURCE.read_text())
    assert data['display_px'] == [160, 80]
    holes = data['holes']
    assert len(holes) == 16
    rows = []
    for x in range(160):
        valid = [y for y in range(80) if inside(-10.85+(x+.5)*21.7/160,
                 5.4-(y+.5)*10.8/80, data['main_window_polygon_mm'])]
        rows.append(min(valid) if valid else 255)
    out = ['// Generated by tools/generate_recoil_geometry.py; do not hand-edit.',
           '// Fusion contract SHA256: '+hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
           '#pragma once', '#include <stdint.h>', 'namespace RecoilGeometry {',
           'constexpr int WIDTH=160, HEIGHT=80, DOT_RADIUS=4, DOT_COUNT=16;',
           'struct Dot { int16_t x, y; uint16_t color; };',
           'static constexpr Dot dots[DOT_COUNT] = {']
    rgb = {'green':(56,220,86), 'amber':(244,188,29), 'red':(243,66,46)}
    for h in holes:
        r,g,b = rgb[h['color']]; color=((r>>3)<<11)|((g>>2)<<5)|(b>>3)
        x,y=h['pixel_x'],h['pixel_y']
        assert abs((-10.85+(x+.5)*21.7/160)-h['x_mm']) < 1e-5
        assert abs((5.4-(y+.5)*10.8/80)-h['y_mm']) < 1e-5
        out.append('    {%d,%d,0x%04X},'%(x,y,color))
    out += ['};', 'static constexpr uint8_t windowTop[WIDTH] = {']
    for i in range(0,160,20):out.append('    '+','.join(map(str,rows[i:i+20]))+',')
    out += ['};','constexpr int WINDOW_BOTTOM=75;', '} // namespace RecoilGeometry','']
    return '\n'.join(out)

if __name__ == '__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
    text=generate()
    if args.check:
        assert TARGET.read_text()==text, 'Firmware geometry differs from CAD contract'
        print('CAD / firmware geometry: 16 points and curved window match')
    else:TARGET.write_text(text)
